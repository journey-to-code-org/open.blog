#!/usr/bin/env node
// Write crates/openblog-cli/src/studio_files.rs: every file under web/studio/, embedded in the
// binary and served under /admin/studio/ (see .claude/skills/studio-architecture).
//
//   node scripts/studio-files.mjs           write the list
//   node scripts/studio-files.mjs --check   exit 1 if the list is out of date (CI and tests)
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";

const here = resolve(dirname(new URL(import.meta.url).pathname), "..");
const root = join(here, "web/studio");
const out = join(here, "crates/openblog-cli/src/studio_files.rs");

const walk = (dir) => readdirSync(dir).sort().flatMap((name) => {
  const path = join(dir, name);
  return statSync(path).isDirectory() ? walk(path) : [path];
});
const files = walk(root).map((path) => relative(root, path).split("\\").join("/")).filter((rel) => !rel.endsWith(".md") && rel !== "zubra/LICENSE");
const lines = files.map((rel) => `    ("${rel}", include_bytes!("../../../web/studio/${rel}")),`);
const text = `// Generated by scripts/studio-files.mjs from web/studio/. Do not edit: run the script.
//! Studio's files (the Admin rebuilt on Zubra UI), embedded in the binary and served under
//! \`/admin/studio/\`.

#[rustfmt::skip]
pub const STUDIO_FILES: &[(&str, &[u8])] = &[
${lines.join("\n")}
];
`;
if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(out, "utf8"); } catch {}
  if (current !== text) {
    console.error("crates/openblog-cli/src/studio_files.rs is out of date: run node scripts/studio-files.mjs");
    process.exit(1);
  }
} else {
  writeFileSync(out, text);
  console.log(`studio_files.rs lists ${files.length} files`);
}
