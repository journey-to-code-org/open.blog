#!/usr/bin/env node
// Write Studio's word catalog where the server and the docs read it (docs/studio-words.md):
//
//   web/studio/words.json   every id with its default, layer, limit and variables, the built-in
//                           variables and the banned list; the server checks a site's changes
//                           against it (crates/openblog-cli/src/admin/studio_words.rs)
//   docs/studio-words.md    the id table, between <!-- words:start --> and <!-- words:end -->
//
//   node scripts/studio-words.mjs           write both
//   node scripts/studio-words.mjs --check   exit 1 if either is out of date (the tests run this)
//
// Run it with scripts/studio-files.mjs after adding or changing an id.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const { catalog, DEFAULT_VARS } = await import(pathToFileURL(join(here, "web/studio/parts/words.js")).href);
const { HER_BANNED_WORDS } = await import(pathToFileURL(join(here, "web/studio/parts/plain-words.js")).href);

const all = catalog();
const ids = Object.keys(all).sort();
const words = Object.fromEntries(ids.map((id) => {
  const { text, layer, max, vars, bare } = all[id];
  return [id, { text, layer, max, vars, ...(bare !== undefined ? { bare } : {}) }];
}));
const json = `${JSON.stringify({ note: "Generated by scripts/studio-words.mjs from web/studio/parts/*-words.js. Do not edit: run the script.", vars: DEFAULT_VARS, banned: HER_BANNED_WORDS, words }, null, 2)}\n`;

const cell = (text) => String(text).replace(/\|/g, "\\|").replace(/\n/g, " ");
const table = [
  "| Id | Layer | Built-in words | Variables | Limit |",
  "| --- | --- | --- | --- | --- |",
  ...ids.map((id) => {
    const e = all[id];
    const shown = e.bare !== undefined ? `${e.text} (with no name: "${e.bare}")` : e.text;
    return `| \`${id}\` | ${e.layer} | ${cell(shown)} | ${e.vars.map((v) => `\`{${v}}\``).join(" ") || "none"} | ${e.max} |`;
  }),
].join("\n");

const docsPath = join(here, "docs/studio-words.md");
const docs = readFileSync(docsPath, "utf8");
const start = "<!-- words:start -->";
const end = "<!-- words:end -->";
if (!docs.includes(start) || !docs.includes(end)) {
  console.error(`docs/studio-words.md needs ${start} and ${end} around the id table`);
  process.exit(1);
}
const newDocs = `${docs.slice(0, docs.indexOf(start) + start.length)}\n${table}\n${docs.slice(docs.indexOf(end))}`;

const jsonPath = join(here, "web/studio/words.json");
if (process.argv.includes("--check")) {
  let stale = [];
  try { if (readFileSync(jsonPath, "utf8") !== json) stale.push("web/studio/words.json"); } catch { stale.push("web/studio/words.json"); }
  if (docs !== newDocs) stale.push("docs/studio-words.md");
  if (stale.length) {
    console.error(`${stale.join(" and ")} out of date: run node scripts/studio-words.mjs`);
    process.exit(1);
  }
} else {
  writeFileSync(jsonPath, json);
  writeFileSync(docsPath, newDocs);
  console.log(`words.json lists ${ids.length} word ids`);
}
